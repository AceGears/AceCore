package com.acecore.app

import android.content.Intent
import android.graphics.Bitmap
import android.os.Environment
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.acecore.app.core.install.GameStorage
import com.acecore.app.core.model.Engine
import com.acecore.app.core.storage.DirectStorage
import com.acecore.app.runtime.rgss.RgssActivity
import com.acecore.app.runtime.rgss.RgssLaunchSpec
import com.acecore.app.runtime.rgss.RgssRuntime
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

/**
 * End-to-end check of the RGSS runtime on a device/emulator: a tiny RPG Maker XP game (generated by
 * ci/make_test_game.rb) is placed in shared storage and started DIRECTLY from there (no private copy), with
 * AceCore's runtime helper preloaded. The test waits for the game's first frame, sends a cheat through the helper's
 * command channel and checks that the game saw it. Needs a build that contains the mkxp-z native libraries and
 * "All files access" granted (CI: appops set ... MANAGE_EXTERNAL_STORAGE allow).
 */
@RunWith(AndroidJUnit4::class)
class RgssDirectLaunchTest {
    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val ctx = instrumentation.targetContext

    private var uiAuto: android.app.UiAutomation? = null

    /** UiAutomation sometimes fails to connect on the first try on a busy emulator; retry a few times. */
    private fun ui(): android.app.UiAutomation {
        uiAuto?.let { return it }
        var last: Throwable? = null
        repeat(6) {
            try { return instrumentation.uiAutomation.also { uiAuto = it } } catch (e: Throwable) { last = e; Thread.sleep(1500) }
        }
        throw last!!
    }

    @Test
    fun startsFromSharedStorage_reachesFirstFrame_andAppliesCheat() {
        assumeTrue("This build has no RGSS native libraries", RgssRuntime.isPresent(ctx))
        assertTrue("All files access must be granted for this test", DirectStorage.hasAccess(ctx))
        ui() // connect before the game starts

        // A non-ASCII folder name, like real libraries ("Pokémon Z"): Ruby's load path contains the game folder, and
        // converting it to a non-UTF-8 filesystem encoding recursed until the engine thread's stack ran out.
        val gameDir = File(Environment.getExternalStorageDirectory(), "AceCoreTest/Pokémon TinyXP")
        gameDir.deleteRecursively()
        copyAsset("tinyxp", gameDir)
        assertTrue(File(gameDir, "Game.ini").isFile && File(gameDir, "Data/Scripts.rxdata").isFile)

        val gameId = 990_001L
        val dataDir = GameStorage.dataDir(ctx, gameId).apply { deleteRecursively() }
        val requestedAt = System.currentTimeMillis()
        val config = mapOf(com.acecore.app.core.config.ConfigKey.GAMEPAD_MODE.id to "always")
        RgssRuntime.writeLaunchFiles(ctx, dataDir, Engine.RPG_MAKER_XP, config, helper = true, cheatsEnabled = true, cheatFlags = emptyMap(), launchRequestedAt = requestedAt)
        val spec = RgssLaunchSpec(
            gameId = gameId, title = "AceCore Test", engine = Engine.RPG_MAKER_XP.name, gamePath = gameDir.absolutePath,
            dataPath = dataDir.absolutePath, config = config, direct = true, helper = true, cheatsEnabled = true, launchRequestedAt = requestedAt,
        )
        ctx.startActivity(Intent(ctx, RgssActivity::class.java).putExtra(RgssLaunchSpec.EXTRA, spec.toJson()).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))

        val helper = RgssRuntime.helperDir(dataDir)
        val ready = File(helper, "ready")
        if (!waitFor(180_000) { ready.exists() }) fail("No first frame within 180 s. " + diagnostics(helper))
        val latency = ready.readText().trim().toLong() - requestedAt
        report("rgss_first_frame_ms", latency)
        // Deep-nesting probe in the test game (ci/make_test_game.rb): large games crashed at start-up when the engine
        // thread's native stack was too small. The game reports "<depth or -reached> <marshal ok> env=..." before its first frame.
        val probe = File(helper, "stack_probe").takeIf { it.exists() }?.readText()?.trim().orEmpty()
        report("rgss_stack_probe", probe)
        val encodings = File(helper, "encodings").takeIf { it.exists() }?.readText()?.trim().orEmpty()
        report("rgss_encodings", encodings)
        assertTrue("Ruby must use UTF-8 for file names: '$encodings'", encodings.startsWith("fs=UTF-8"))
        val rgss1 = File(helper, "rgss1").takeIf { it.exists() }?.readText()?.trim().orEmpty()
        report("rgss1_compat", rgss1)
        assertTrue("Ruby 1.8 'when x:' scripts must be adapted: '$rgss1'", rgss1.startsWith("r18=ok "))
        assertTrue("Top-level class variables (RGSS1 / Ruby 1.8) must work: '$rgss1'", rgss1.contains(" cvar=7 "))
        assertTrue("Ruby 1.8 strings (\"A\"[0] == 65) must work in an RPG Maker XP game: '$rgss1'", rgss1.contains(" s18=ok "))
        assertTrue("Marshal.load from a reader returning more than asked must load intact (Pokémon Flux): '$rgss1'", rgss1.contains("marshal=ok"))
        assertTrue("Essentials Win32API start-up calls must work: '$rgss1'", rgss1.contains(" win32=true "))
        assertTrue("Display layout modes (Fill / Zoom / Original, position) must be available in the engine: '$rgss1'", rgss1.contains("layout=ok"))
        assertTrue("Deep recursion through C methods must reach 3000 levels: '$probe' " + diagnostics(helper), probe.startsWith("3000 "))
        assertTrue("Marshal.load of 2000-deep data must work: '$probe'", probe.split(" ").getOrNull(1) == "true")
        Thread.sleep(1500)
        screenshot("rgss_game.png")

        File(helper, "cmd").writeText("1\tgold\tset\t777\n")
        if (!waitFor(60_000) { File(helper, "test_cheat_ok").exists() }) fail("The game didn't see the cheat. " + diagnostics(helper))
        val result = File(helper, "result").takeIf { it.exists() }?.readText().orEmpty()
        assertTrue("Helper result: $result", result.startsWith("1\tok"))
        assertTrue("State should list the gold capability", File(helper, "state").readText().contains("gold"))

        // ---- Walking: hold the on-screen D-pad (real touch events) and check the character moves, then stops.
        if (!waitFor(30_000) { File(helper, "walk_ready").exists() && File(helper, "dpad").exists() }) fail("Walk phase not reached. " + diagnostics(helper))
        val pad = File(helper, "dpad").readText().trim().split(' ').map { it.toInt() }
        val x = (pad[0] + pad[2]) / 2f
        val y = pad[1] + (pad[3] - pad[1]) * 0.83f       // lower arm of the D-pad = Down
        // Injected touches occasionally don't reach a just-started window on the CI emulator; retry the hold (up to 3×)
        // until the game has seen Down at least once. Every attempt is reported.
        var before = walk(helper)
        var attempts = 0
        var seen: Boolean
        do {
            attempts++
            before = walk(helper)
            report("walk_before_$attempts", before.joinToString(" "))
            val downTime = android.os.SystemClock.uptimeMillis()
            touch(downTime, android.view.MotionEvent.ACTION_DOWN, x, y)
            try {
                Thread.sleep(1200)
                touch(downTime, android.view.MotionEvent.ACTION_MOVE, x, y + 1)
                if (attempts == 1) { screenshot("rgss_walk.png"); smallShot("rgss_walk_small.jpg") }
                Thread.sleep(1800)
            } finally {
                touch(downTime, android.view.MotionEvent.ACTION_UP, x, y + 1)
            }
            seen = walk(helper).getOrElse(6) { "0" }.toInt() > before.getOrElse(6) { "0" }.toInt()
            if (!seen) Thread.sleep(1500)
        } while (!seen && attempts < 3)
        report("walk_attempts", attempts)
        val held = walk(helper)
        report("walk_while_held", held.joinToString(" "))
        Thread.sleep(1500)
        val released = walk(helper)
        Thread.sleep(1000)
        val later = walk(helper)
        report("walk_after_release", later.joinToString(" "))
        // walk = steps, dir4, facing, frames skipped by the "delta > 0.25 s" rule, frames, uptime class, frames with
        // Down held, seconds in the walk phase
        report("touch_at", "$x,$y pad=${pad.joinToString(",")}")
        val info = "before=${before.joinToString(" ")} held=${held.joinToString(" ")}"
        assertTrue("System.uptime must be seconds (Float): $info", held[5] == "Float")
        assertTrue("D-pad Down must reach the game (Input.dir4 / press?(DOWN)): $info", held.getOrElse(6) { "0" }.toInt() > before.getOrElse(6) { "0" }.toInt())
        assertTrue("Character should face down: $info", held[2] == "2")
        // Essentials walks one tile per 0.25 s of held time, counted only on frames shorter than 0.25 s. The CI
        // emulator runs ARM code through translation (often < 10 fps), so require at least one step there.
        assertTrue("Character should walk: $info", held[0].toInt() - before[0].toInt() >= 1)

        // ---- Fast-forward: the same hold at 3× must cover clearly more ground (the game clock and frame counter
        // both run faster; see acecore_compat.rb › Tools).
        val normalRate = (held[0].toInt() - before[0].toInt()) / (held[7].toDouble() - before.getOrElse(7) { "0" }.toDouble()).coerceAtLeast(0.5)
        File(helper, "speed").writeText("speed=3\naudio=quiet\n")
        Thread.sleep(1500)
        val ffBefore = walk(helper)
        val t0 = android.os.SystemClock.uptimeMillis()
        touch(t0, android.view.MotionEvent.ACTION_DOWN, x, y)
        try { Thread.sleep(2500) } finally { touch(t0, android.view.MotionEvent.ACTION_UP, x, y + 1) }
        val ffAfter = walk(helper)
        // Ends the game's walking phase. (It used to be written before the fast-forward part, so the game had
        // already stopped walking and fast-forward always measured 0 steps.)
        File(helper, "walk_done").writeText("1")
        File(helper, "speed").writeText("speed=1\naudio=quiet\n")
        val realSeconds = (android.os.SystemClock.uptimeMillis() - t0) / 1000.0
        val ffRate = (ffAfter[0].toInt() - ffBefore[0].toInt()) / realSeconds
        report("fast_forward", "normal=%.2f steps/s, 3x=%.2f steps/s (before=%s after=%s)".format(normalRate, ffRate, ffBefore.joinToString(" "), ffAfter.joinToString(" ")))
        assertTrue("Fast-forward 3× should walk clearly faster: normal=$normalRate/s ff=$ffRate/s " +
            "before=${ffBefore.joinToString(" ")} after=${ffAfter.joinToString(" ")} " + diagnostics(helper), ffRate >= normalRate * 1.8)
        assertTrue("Direction must clear on release: ${released.joinToString(" ")}", released[1] == "0")
        assertTrue("Character must stop after release: $released / $later", later[0] == released[0])
    }

    private fun walk(helper: File): List<String> =
        File(helper, "walk").takeIf { it.exists() }?.readText()?.trim()?.split(' ') ?: listOf("0", "0", "0", "0", "0", "?", "0", "0")

    private fun touch(downTime: Long, action: Int, x: Float, y: Float) {
        val ev = android.view.MotionEvent.obtain(downTime, android.os.SystemClock.uptimeMillis(), action, x, y, 0)
        ev.source = android.view.InputDevice.SOURCE_TOUCHSCREEN
        assertTrue("Touch injection failed", ui().injectInputEvent(ev, true))
        ev.recycle()
    }

    private fun copyAsset(path: String, target: File) {
        val am = instrumentation.context.assets
        val children = am.list(path).orEmpty()
        if (children.isEmpty()) {
            target.parentFile?.mkdirs()
            am.open(path).use { input -> target.outputStream().use { input.copyTo(it) } }
        } else {
            target.mkdirs()
            children.forEach { copyAsset("$path/$it", File(target, it)) }
        }
    }

    private fun waitFor(ms: Long, cond: () -> Boolean): Boolean {
        val until = System.currentTimeMillis() + ms
        while (System.currentTimeMillis() < until) { if (cond()) return true; Thread.sleep(250) }
        return cond()
    }

    private fun diagnostics(helper: File): String = listOf("test_error", "error", "log", "test_started", "stack_probe", "speed").joinToString(" | ") { n ->
        "$n=" + (File(helper, n).takeIf { it.exists() }?.readText()?.take(400) ?: "-")
    } + " | engine_output=" + (File(helper, "engine_output.txt").takeIf { it.exists() }?.readText()
        ?.let { o -> o.substring(maxOf(0, o.indexOf("[BUG]") - 200)).take(1500) } ?: "-")

    private fun report(key: String, value: Any) {
        val dir = File(ctx.getExternalFilesDir(null), "testresults").apply { mkdirs() }
        File(dir, "metrics.txt").appendText("$key=$value\n")
        android.util.Log.i("AceCoreTest", "$key=$value")
    }

    /** A small JPEG the CI job can show inline (as base64 in a notice). */
    private fun smallShot(name: String) {
        val bmp = ui().takeScreenshot() ?: return
        val small = Bitmap.createScaledBitmap(bmp, 360, (360f * bmp.height / bmp.width).toInt(), true)
        val dir = File(ctx.getExternalFilesDir(null), "testresults").apply { mkdirs() }
        File(dir, name).outputStream().use { small.compress(Bitmap.CompressFormat.JPEG, 45, it) }
    }

    private fun screenshot(name: String) {
        val bmp = ui().takeScreenshot() ?: return
        val dir = File(ctx.getExternalFilesDir(null), "testresults").apply { mkdirs() }
        File(dir, name).outputStream().use { bmp.compress(Bitmap.CompressFormat.PNG, 100, it) }
    }
}
