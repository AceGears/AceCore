package com.acecore.app

import android.content.Intent
import android.graphics.Bitmap
import android.os.Environment
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.acecore.app.core.install.GameStorage
import com.acecore.app.core.model.Engine
import com.acecore.app.core.storage.DirectStorage
import com.acecore.app.runtime.rgss.RgssActivity
import com.acecore.app.runtime.rgss.RgssLaunchSpec
import com.acecore.app.runtime.rgss.RgssRuntime
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Assume.assumeTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

/**
 * End-to-end check of the RGSS runtime on a device/emulator: a tiny RPG Maker XP game (generated by
 * ci/make_test_game.rb) is placed in shared storage and started DIRECTLY from there (no private copy), with
 * AceCore's runtime helper preloaded. The test waits for the game's first frame, sends a cheat through the helper's
 * command channel and checks that the game saw it. Needs a build that contains the mkxp-z native libraries and
 * "All files access" granted (CI: appops set ... MANAGE_EXTERNAL_STORAGE allow).
 */
@RunWith(AndroidJUnit4::class)
class RgssDirectLaunchTest {
    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val ctx = instrumentation.targetContext

    @Test
    fun startsFromSharedStorage_reachesFirstFrame_andAppliesCheat() {
        assumeTrue("This build has no RGSS native libraries", RgssRuntime.isPresent(ctx))
        assertTrue("All files access must be granted for this test", DirectStorage.hasAccess(ctx))

        val gameDir = File(Environment.getExternalStorageDirectory(), "AceCoreTest/TinyXP")
        gameDir.deleteRecursively()
        copyAsset("tinyxp", gameDir)
        assertTrue(File(gameDir, "Game.ini").isFile && File(gameDir, "Data/Scripts.rxdata").isFile)

        val gameId = 990_001L
        val dataDir = GameStorage.dataDir(ctx, gameId).apply { deleteRecursively() }
        val requestedAt = System.currentTimeMillis()
        RgssRuntime.writeLaunchFiles(ctx, dataDir, Engine.RPG_MAKER_XP, emptyMap(), helper = true, cheatsEnabled = true, cheatFlags = emptyMap(), launchRequestedAt = requestedAt)
        val spec = RgssLaunchSpec(
            gameId = gameId, title = "AceCore Test", engine = Engine.RPG_MAKER_XP.name, gamePath = gameDir.absolutePath,
            dataPath = dataDir.absolutePath, config = emptyMap(), direct = true, helper = true, cheatsEnabled = true, launchRequestedAt = requestedAt,
        )
        ctx.startActivity(Intent(ctx, RgssActivity::class.java).putExtra(RgssLaunchSpec.EXTRA, spec.toJson()).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))

        val helper = RgssRuntime.helperDir(dataDir)
        val ready = File(helper, "ready")
        if (!waitFor(180_000) { ready.exists() }) fail("No first frame within 180 s. " + diagnostics(helper))
        val latency = ready.readText().trim().toLong() - requestedAt
        report("rgss_first_frame_ms", latency)
        Thread.sleep(1500)
        screenshot("rgss_game.png")

        File(helper, "cmd").writeText("1\tgold\tset\t777\n")
        if (!waitFor(60_000) { File(helper, "test_cheat_ok").exists() }) fail("The game didn't see the cheat. " + diagnostics(helper))
        val result = File(helper, "result").takeIf { it.exists() }?.readText().orEmpty()
        assertTrue("Helper result: $result", result.startsWith("1\tok"))
        assertTrue("State should list the gold capability", File(helper, "state").readText().contains("gold"))
    }

    private fun copyAsset(path: String, target: File) {
        val am = instrumentation.context.assets
        val children = am.list(path).orEmpty()
        if (children.isEmpty()) {
            target.parentFile?.mkdirs()
            am.open(path).use { input -> target.outputStream().use { input.copyTo(it) } }
        } else {
            target.mkdirs()
            children.forEach { copyAsset("$path/$it", File(target, it)) }
        }
    }

    private fun waitFor(ms: Long, cond: () -> Boolean): Boolean {
        val until = System.currentTimeMillis() + ms
        while (System.currentTimeMillis() < until) { if (cond()) return true; Thread.sleep(250) }
        return cond()
    }

    private fun diagnostics(helper: File): String = listOf("test_error", "error", "log", "test_started").joinToString(" | ") { n ->
        "$n=" + (File(helper, n).takeIf { it.exists() }?.readText()?.take(400) ?: "-")
    }

    private fun report(key: String, value: Any) {
        val dir = File(ctx.getExternalFilesDir(null), "testresults").apply { mkdirs() }
        File(dir, "metrics.txt").appendText("$key=$value\n")
        android.util.Log.i("AceCoreTest", "$key=$value")
    }

    private fun screenshot(name: String) {
        val bmp = instrumentation.uiAutomation.takeScreenshot() ?: return
        val dir = File(ctx.getExternalFilesDir(null), "testresults").apply { mkdirs() }
        File(dir, name).outputStream().use { bmp.compress(Bitmap.CompressFormat.PNG, 100, it) }
    }
}
